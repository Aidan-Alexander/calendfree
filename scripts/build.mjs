// Builds the site into dist/, under BASE_PATH if it's set (e.g. BASE_PATH=/meet serves everything at /meet/...).
// Also writes the function's route list, which Netlify needs as a fixed value.
// Netlify runs this on every deploy; run it yourself with `node scripts/build.mjs`.
import { cpSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, extname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { normaliseBase } from '../lib/config.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const base = normaliseBase(process.env.BASE_PATH);
if (base && !/^(\/[a-z0-9-]+)+$/i.test(base)) throw new Error(`BASE_PATH "${base}" should look like /meet`);

// Where every copy's "Send feedback" link goes: the project's own board, unless a fork sets its own.
const feedbackUrl = process.env.FEEDBACK_URL || 'https://aidan-alexander.com/meet/feedback/';

const dist = join(root, 'dist');
rmSync(dist, { recursive: true, force: true });
const out = join(dist, base);
mkdirSync(out, { recursive: true });
cpSync(join(root, 'public'), out, { recursive: true });

// Put the base path into every link and fetch.
const walk = (dir) => readdirSync(dir).flatMap((f) => (statSync(join(dir, f)).isDirectory() ? walk(join(dir, f)) : [join(dir, f)]));
for (const file of walk(out)) {
  if (!['.html', '.js', '.css'].includes(extname(file))) continue;
  writeFileSync(file, readFileSync(file, 'utf8').replaceAll('{{BASE}}', base).replaceAll('{{FEEDBACK_URL}}', feedbackUrl));
}

// Any path that isn't a file, /api/* or /auth/* is a booking page: <base>/<page-name>#<minutes>
const redirects = [
  ...(base ? [`/  ${base}/  302`, `${base}  ${base}/book.html  200`] : []),
  `${base}/*  ${base}/book.html  200`,
];
writeFileSync(join(dist, '_redirects'), `${redirects.join('\n')}\n`);

mkdirSync(join(root, 'netlify/functions'), { recursive: true });
writeFileSync(
  join(root, 'netlify/functions/api.mjs'),
  `// Generated by scripts/build.mjs (BASE_PATH="${base}"). Edit lib/router.mjs instead.
import handle from '../../lib/router.mjs';

export default handle;

export const config = { path: ['${base}/api/*', '${base}/auth/*'] };
`,
);

console.log(`Built dist/ with base path "${base || '/'}"`);
